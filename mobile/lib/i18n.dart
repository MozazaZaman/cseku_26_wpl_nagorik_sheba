import 'package:flutter/material.dart';
import 'package:shared_preferences/shared_preferences.dart';

class Lang extends ChangeNotifier {
  static const _key = 'ns_lang';
  String _lang = 'en';
  bool _ready = false;

  String get lang => _lang;
  bool get isBn => _lang == 'bn';
  bool get ready => _ready;

  Future<void> load() async {
    final p = await SharedPreferences.getInstance();
    _lang = p.getString(_key) ?? 'en';
    _ready = true;
    notifyListeners();
  }

  Future<void> toggle() async {
    _lang = _lang == 'en' ? 'bn' : 'en';
    final p = await SharedPreferences.getInstance();
    await p.setString(_key, _lang);
    notifyListeners();
  }

  String t(String key) => _dict[_lang]?[key] ?? _dict['en']?[key] ?? key;

  String toggleLabel() => isBn ? 'Translate to English' : 'বাংলায় অনুবাদ';
  String shortLabel() => isBn ? 'EN' : 'বাংলা';
}

