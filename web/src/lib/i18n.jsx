const LangCtx = createContext(null);

export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('ns_lang') || 'en');

  useEffect(() => {
    localStorage.setItem('ns_lang', lang);
    document.documentElement.lang = lang === 'bn' ? 'bn' : 'en';
    document.documentElement.classList.toggle('bn-mode', lang === 'bn');
  }, [lang]);

  const toggle = () => setLang((l) => (l === 'en' ? 'bn' : 'en'));
  const t = (key) => dict[lang]?.[key] ?? dict.en[key] ?? key;

  return <LangCtx.Provider value={{ lang, setLang, toggle, t }}>{children}</LangCtx.Provider>;
}

export function useLang() {
  return useContext(LangCtx);
}

