// Human-readable role for the identity pill / drawer: citizens are just
// "Citizen"; staff get their hierarchy role ("Junior Staff", "Mayor"…).
export function roleLabel(user, t) {
  if (!user) return '';
  if (user.role === 'super_admin') return t('role.superadmin');
  if (user.role !== 'staff') return t('role.citizen');
  return t(`role.${user.staff_role || 'field'}`) || user.staff_role || 'staff';
}

// Full title for the drawer identity block, e.g.
// "Mayor of Khulna City Corporation" — authority name comes from the JWT.
export function fullRoleTitle(user, t) {
  if (!user) return '';
  const role = roleLabel(user, t);
  if (user.role === 'staff' && user.authority_name) {
    return t('role.full')
      .replace('{role}', role)
      .replace('{authority}', user.authority_name);
  }
  return role;
}
